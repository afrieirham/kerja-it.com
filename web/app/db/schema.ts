import { randomUUID } from "node:crypto";
import { sql } from "drizzle-orm";
import {
	boolean,
	index,
	integer,
	pgTable,
	text,
	timestamp,
	uniqueIndex,
} from "drizzle-orm/pg-core";

export const job = pgTable(
	"Job",
	{
		id: text()
			.primaryKey()
			.notNull()
			.$defaultFn(() => randomUUID()),
		url: text(),
		title: text().notNull(),
		description: text().notNull(),
		createdAt: timestamp({ precision: 3, mode: "string" })
			.default(sql`CURRENT_TIMESTAMP`)
			.notNull(),
		updatedAt: timestamp({ precision: 3, mode: "string" })
			.notNull()
			.$defaultFn(() => new Date().toISOString()),
		source: text().notNull(),
		company: text(),
		location: text(),
		role: text(),
		seniority: text(),
		salary: text(),
		postedAt: timestamp({ precision: 3, mode: "string" }),
		// "published" (default — everything scraped) or "pending" (direct
		// posts awaiting review in /admin).
		status: text().notNull().default("published"),
		postedById: text().references(() => user.id, { onDelete: "set null" }),
		// Structured salary from direct posts, RM per month (min = max for an
		// exact salary). The formatted text also lands in `salary` for display.
		salaryMin: integer(),
		salaryMax: integer(),
		// Direct-post-only fields — deliberately NOT filter dimensions (see
		// job-attributes.ts for the option lists). Scraped rows stay null.
		city: text(),
		arrangement: text(), // remote | hybrid | on-site
		employmentType: text(), // full-time | part-time | internship | contract
		// Email-only applications: url is null and candidates apply by email.
		applyEmail: text(),
		// On-site page slug, direct posts only ("title-company-x7k2p9"). Null
		// for scraped jobs — they have no /jobs/:slug page.
		slug: text(),
		// Paid posts consumed a pack credit and get the featured perks;
		// featuredUntil is stamped at approval (30d), never at submission.
		isPaid: boolean().notNull().default(false),
		featuredUntil: timestamp({ precision: 3, mode: "string" }),
	},
	(table) => [
		uniqueIndex("Job_url_key").using(
			"btree",
			table.url.asc().nullsLast().op("text_ops"),
		),
		uniqueIndex("Job_slug_key").using(
			"btree",
			table.slug.asc().nullsLast().op("text_ops"),
		),
	],
);

export const jobOrder = pgTable(
	"JobOrder",
	{
		id: text()
			.primaryKey()
			.notNull()
			.$defaultFn(() => randomUUID()),
		// Unique: webhook idempotency — a replayed checkout.session.completed
		// must not grant the pack twice.
		stripeSessionId: text().notNull(),
		userId: text()
			.notNull()
			.references(() => user.id, { onDelete: "cascade" }),
		packPosts: integer().notNull(),
		amountCents: integer().notNull(),
		status: text().notNull().default("pending"), // pending | paid | failed
		createdAt: timestamp({ precision: 3, mode: "string" })
			.default(sql`CURRENT_TIMESTAMP`)
			.notNull(),
	},
	(table) => [
		uniqueIndex("JobOrder_stripeSessionId_key").using(
			"btree",
			table.stripeSessionId.asc().nullsLast().op("text_ops"),
		),
	],
);

// 1:1 with the auth user — most employers are a single company. Jobs keep
// their own `company` text snapshot; this only prefills the form.
export const companyProfile = pgTable("CompanyProfile", {
	userId: text()
		.primaryKey()
		.notNull()
		.references(() => user.id, { onDelete: "cascade" }),
	name: text().notNull(),
	website: text(),
	updatedAt: timestamp({ precision: 3, mode: "string" })
		.notNull()
		.$defaultFn(() => new Date().toISOString()),
});

// --- better-auth core tables ----------------------------------------------
// Generated by @better-auth/cli (better-auth v1.6) and kept verbatim except
// formatting. Lowercase quoted names are intentional — they are better-auth's
// defaults, and renaming models adds config surface for zero gain. PascalCase
// remains the convention for app-owned tables.

export const user = pgTable("user", {
	id: text("id").primaryKey(),
	name: text("name").notNull(),
	email: text("email").notNull().unique(),
	emailVerified: boolean("email_verified").default(false).notNull(),
	image: text("image"),
	createdAt: timestamp("created_at").defaultNow().notNull(),
	updatedAt: timestamp("updated_at")
		.defaultNow()
		.$onUpdate(() => new Date())
		.notNull(),
});

export const session = pgTable(
	"session",
	{
		id: text("id").primaryKey(),
		expiresAt: timestamp("expires_at").notNull(),
		token: text("token").notNull().unique(),
		createdAt: timestamp("created_at").defaultNow().notNull(),
		updatedAt: timestamp("updated_at")
			.$onUpdate(() => new Date())
			.notNull(),
		ipAddress: text("ip_address"),
		userAgent: text("user_agent"),
		userId: text("user_id")
			.notNull()
			.references(() => user.id, { onDelete: "cascade" }),
	},
	(table) => [index("session_userId_idx").on(table.userId)],
);

export const account = pgTable(
	"account",
	{
		id: text("id").primaryKey(),
		accountId: text("account_id").notNull(),
		providerId: text("provider_id").notNull(),
		userId: text("user_id")
			.notNull()
			.references(() => user.id, { onDelete: "cascade" }),
		accessToken: text("access_token"),
		refreshToken: text("refresh_token"),
		idToken: text("id_token"),
		accessTokenExpiresAt: timestamp("access_token_expires_at"),
		refreshTokenExpiresAt: timestamp("refresh_token_expires_at"),
		scope: text("scope"),
		password: text("password"),
		createdAt: timestamp("created_at").defaultNow().notNull(),
		updatedAt: timestamp("updated_at")
			.$onUpdate(() => new Date())
			.notNull(),
	},
	(table) => [index("account_userId_idx").on(table.userId)],
);

